using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Manta.Generators.View;

[Generator]
sealed class ViewGenerator : IIncrementalGenerator
{
    const string ViewAttributeFullName = "Manta.Reactive.Views.ViewAttribute`1";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var provider = context.SyntaxProvider.ForAttributeWithMetadataName(
            ViewAttributeFullName,
            static (node, _) => node is ClassDeclarationSyntax,
            static (ctx, _) => GetViewModelInfo(ctx));

        context.RegisterSourceOutput(provider.Collect(), Execute);
    }

    static ViewModelInfo? GetViewModelInfo(GeneratorAttributeSyntaxContext context)
    {
        var classSymbol = context.TargetSymbol as INamedTypeSymbol;
        if (classSymbol is null)
            return null;

        foreach (var attribute in classSymbol.GetAttributes())
        {
            var attrClass = attribute.AttributeClass;
            if (attrClass is null || attrClass.IsGenericType is false)
                continue;

            var original = attrClass.OriginalDefinition;
            if (original.ToDisplayString() != "Manta.Reactive.Views.ViewAttribute<T>")
                continue;

            var typeArg = attrClass.TypeArguments[0];
            if (typeArg is not INamedTypeSymbol viewType)
                continue;

            var classNamespace = classSymbol.ContainingNamespace.IsGlobalNamespace
                ? null
                : classSymbol.ContainingNamespace.ToDisplayString();

            var isInternal = IsCreateViewInternal(classSymbol);

            return new(
                classNamespace,
                classSymbol.Name,
                viewType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
                isInternal);
        }

        return null;
    }

    static bool IsCreateViewInternal(INamedTypeSymbol classSymbol)
    {
        var current = classSymbol.BaseType;
        while (current is not null)
        {
            foreach (var member in current.GetMembers("CreateView"))
                if (member is IMethodSymbol { DeclaredAccessibility: Accessibility.ProtectedOrInternal })
                    return SymbolEqualityComparer.Default.Equals(classSymbol.ContainingAssembly, current.ContainingAssembly);

            current = current.BaseType;
        }

        return false;
    }

    static void Execute(SourceProductionContext context, ImmutableArray<ViewModelInfo?> items)
    {
        foreach (var info in items)
        {
            if (info is null)
                continue;

            var modifier = info.IsInternal ? "protected internal" : "protected";

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated />");
            sb.AppendLine("#nullable enable");
            sb.AppendLine();
            sb.AppendLine("using Manta.Reactive.Views;");
            sb.AppendLine();

            if (info.Namespace is not null)
            {
                sb.AppendLine($"namespace {info.Namespace};");
                sb.AppendLine();
            }

            sb.AppendLine($"partial class {info.ClassName}");
            sb.AppendLine("{");
            sb.AppendLine($"    {modifier} override global::Manta.Controls.MView CreateView()");
            sb.AppendLine("    {");
            sb.AppendLine($"        return new {info.ViewTypeFullName}();");
            sb.AppendLine("    }");
            sb.AppendLine();
            sb.AppendLine($"    {info.ViewTypeFullName} GetView()");
            sb.AppendLine("    {");
            sb.AppendLine($"        if (this.GetViewCore() is {info.ViewTypeFullName} view)");
            sb.AppendLine("            return view;");
            sb.AppendLine();
            sb.AppendLine($"        throw new InvalidOperationException($\"View is not of type {{typeof({info.ViewTypeFullName})}}\");");
            sb.AppendLine("    }");
            sb.AppendLine("}");

            var hintName = info.Namespace is not null
                ? $"{info.Namespace}.{info.ClassName}.g.cs"
                : $"{info.ClassName}.g.cs";

            context.AddSource(hintName, sb.ToString());
        }
    }

    sealed class ViewModelInfo(string? ns, string className, string viewTypeFullName, bool isInternal)
    {
        public string? Namespace { get; } = ns;
        public string ClassName { get; } = className;
        public string ViewTypeFullName { get; } = viewTypeFullName;
        public bool IsInternal { get; } = isInternal;
    }
}
