using System.Collections.Immutable;
using System.Text;
using Axe.I18N.Core;
using Axe.I18N.Generator.Models;
using Microsoft.CodeAnalysis;
using YamlDotNet.Core;
using YamlDotNet.Core.Events;

namespace Axe.I18N.Generator;

sealed class GeneratorCore
{
    readonly SourceProductionContext _context;
    readonly string _assemblyName;
    readonly Dictionary<string, AdditionalText> _files;

    public LangConfig Config { get; }
    public Dictionary<LangType, LangData> Data { get; }
    public LangData BaseData { get; }
    public LangData CommentData { get; }

    public GeneratorCore(SourceProductionContext context, Compilation compilation, ImmutableArray<AdditionalText> files)
    {
        _context = context;
        _assemblyName = compilation.AssemblyName ?? throw new InvalidOperationException("Unable to retrieve the assembly name of the project");

        _files = FilterFiles(files);

        Config = ParserConfig();
        Data = ParserFiles();

        if (Data.TryGetValue(Config.Base, out var baseData) is false)
            throw new InvalidOperationException($"The base language file '{Config.Base}.yml' is missing.");
        BaseData = baseData;

        if (Data.TryGetValue(Config.Comment, out var commentData) is false)
            throw new InvalidOperationException($"The comment language file '{Config.Comment}.yml' is missing.");
        CommentData = commentData;

        Data.Remove(Config.Base);
    }

    LangConfig ParserConfig()
    {
        if (_files.TryGetValue("@config", out var configText) is false)
            return new();

        var yml = configText.GetText()?.ToString();
        if (yml is not null)
            return LangConfig.Load(yml);

        return new();
    }

    Dictionary<LangType, LangData> ParserFiles()
    {
        var data = new Dictionary<LangType, LangData>();

        foreach (var langType in Enum.GetValues(typeof(LangType)).Cast<LangType>())
            if (_files.TryGetValue($"{langType}", out var file))
            {
                var langData = new LangData(file);
                ParserFile(langData);
                data.Add(langType, langData);
            }

        return data;
    }

    void ParserFile(LangData data)
    {
        var yml = data.File.GetText()?.ToString();
        if (yml is null)
        {
            _context.WriteWarning($"The file '{data.File.Path}' is empty.", data.Location);
            return;
        }

        var yamlParser = new Parser(new StringReader(yml));

        LangValue? item = null;

        while (yamlParser.MoveNext())
        {
            if (yamlParser.Current is not Scalar scalar)
                continue;

            if (item is null)
            {
                item = new()
                {
                    Key = scalar.Value,
                    KeyLocation = Location.Create(data.File.Path, new((int)scalar.Start.Index, (int)(scalar.End.Index - scalar.Start.Index)), new(new((int)scalar.Start.Line - 1, (int)scalar.Start.Column - 1), new((int)scalar.End.Line - 1, (int)scalar.End.Column - 1)))
                };
            }
            else
            {
                item.Value = scalar.Value;

                data.Values.Add(item.Key, item);
                item = null;
            }
        }
    }

    static Dictionary<string, AdditionalText> FilterFiles(ImmutableArray<AdditionalText> files)
    {
        var dic = new Dictionary<string, AdditionalText>();

        foreach (var file in files)
        {
            var dirName = Path.GetFileName(Path.GetDirectoryName(file.Path) ?? string.Empty);
            if (dirName != "Langs")
                continue;

            var extName = Path.GetExtension(file.Path);
            if (string.Equals(extName, ".yml", StringComparison.OrdinalIgnoreCase) is false && string.Equals(extName, ".yaml", StringComparison.OrdinalIgnoreCase) is false)
                continue;

            var fileName = Path.GetFileNameWithoutExtension(file.Path);
            dic.Add(fileName, file);
        }

        return dic;
    }

    public void CheckMissing()
    {
        foreach (var data in Data.Values)
        foreach (var baseData in BaseData.Values)
            if (data.Values.ContainsKey(baseData.Key) is false)
                _context.WriteMissing($"Not found [{baseData.Key}] in the language file.", data.Location);
    }

    public void CheckRedundant()
    {
        foreach (var data in Data.Values)
        foreach (var dataItem in data.Values)
            if (BaseData.Values.ContainsKey(dataItem.Key) is false)
                _context.WriteRedundant($"The key [{dataItem.Key}] is redundant in the language file.", dataItem.Value.KeyLocation);
    }

    public void GenerateLangKey()
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("//");
        sb.AppendLine($"// The list is generated based on {Config.Base}.yml. ");
        sb.AppendLine($"// Generator version: {GeneratorConfigs.GeneratorVersion}");
        sb.AppendLine();
        sb.AppendLine("using System.Reflection;");
        sb.AppendLine();
        sb.AppendLine($"namespace {_assemblyName}.Langs;");
        sb.AppendLine();

        if (string.Equals(Config.Modifier, "private", StringComparison.OrdinalIgnoreCase))
            sb.AppendLine($"enum {Config.ClassName}");
        else
            sb.AppendLine($"{Config.Modifier} enum {Config.ClassName}");

        sb.AppendLine("{");

        foreach (var baseValue in BaseData.Values)
        {
            sb.AppendLine("    /// <summary>");
            if (CommentData.Values.TryGetValue(baseValue.Key, out var comment))
                sb.AppendLine($"    ///     {comment.Value}");
            else
                sb.AppendLine($"    ///     {baseValue.Value}");
            sb.AppendLine("    /// </summary>");
            sb.AppendLine($"    {baseValue.Key},");
            sb.AppendLine();
        }

        sb.AppendLine("}");

        _context.AddSource($"{Config.ClassName}.g.cs", sb.ToString());
    }

    public void GenerateAssemblyInfo()
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("//");
        sb.AppendLine($"// The list is generated based on {Config.Base}.yml. ");
        sb.AppendLine($"// Generator version: {GeneratorConfigs.GeneratorVersion}");
        sb.AppendLine();
        sb.AppendLine("using Avalonia.Metadata;");
        sb.AppendLine();
        sb.AppendLine($"[assembly: XmlnsDefinition(\"https://github.com/avaloniaui\", \"{_assemblyName}.Langs\")]");

        _context.AddSource($"{Config.ClassName}.AssemblyInfo.g.cs", sb.ToString());
    }
}
