using System.Collections.Immutable;
using System.Text;
using Axe.Icons.Generator.Models;
using Microsoft.CodeAnalysis;

namespace Axe.Icons.Generator;

sealed class GeneratorCore
{
    readonly SourceProductionContext _context;
    readonly string _assemblyName;
    readonly Dictionary<string, AdditionalText> _files;

    public GeneratorCore(SourceProductionContext context, Compilation compilation, ImmutableArray<AdditionalText> files)
    {
        _context = context;
        _assemblyName = compilation.AssemblyName ?? throw new InvalidOperationException("Unable to retrieve the assembly name of the project");
        _files = FilterFiles(files);

        ParserIcons();
    }

    static Dictionary<string, AdditionalText> FilterFiles(ImmutableArray<AdditionalText> files)
    {
        var dic = new Dictionary<string, AdditionalText>();

        foreach (var file in files)
        {
            var dirName = Path.GetFileName(Path.GetDirectoryName(file.Path) ?? string.Empty);
            if (dirName != "Icons")
                continue;

            var extName = Path.GetExtension(file.Path);
            if (string.Equals(extName, ".svg", StringComparison.OrdinalIgnoreCase) is false)
                continue;

            var fileName = Path.GetFileNameWithoutExtension(file.Path);
            dic.Add(fileName, file);
        }

        return dic;
    }

    readonly List<IconData> _icons = new();

    void ParserIcons()
    {
        foreach (var keyValuePair in _files)
        {
            var key = keyValuePair.Key.Replace("-", string.Empty);
            var iconData = new IconData(key);
            _icons.Add(iconData);
        }
    }

    public void GenerateIconData()
    {
    }

    public void GenerateIconKey()
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("//");
        sb.AppendLine($"// Generator version: {GeneratorConfigs.GeneratorVersion}");
        sb.AppendLine();
        sb.AppendLine("using System.Reflection;");
        sb.AppendLine();
        sb.AppendLine($"namespace {_assemblyName}.Icons;");
        sb.AppendLine();

        sb.AppendLine("enum IconKeys");
        sb.AppendLine("{");

        foreach (var icon in _icons)
        {
            sb.AppendLine($"    {icon.Key},");
            sb.AppendLine();
        }

        sb.AppendLine("}");

        _context.AddSource("Icons.Keys.g.cs", sb.ToString());
    }

    public void GenerateAssemblyInfo()
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("//");
        sb.AppendLine($"// Generator version: {GeneratorConfigs.GeneratorVersion}");
        sb.AppendLine();
        sb.AppendLine("using Avalonia.Metadata;");
        sb.AppendLine();
        sb.AppendLine($"[assembly: XmlnsDefinition(\"https://github.com/avaloniaui\", \"{_assemblyName}.Icons\")]");

        _context.AddSource("Icons.AssemblyInfo.g.cs", sb.ToString());
    }
}
